#!/usr/bin/env python3
"""Record SDK signatures/annotations without loading IDE bytecode.
Usage: inspect-editor-sdk.py OUTPUT_DIR SDK_DIR [SDK_DIR ...]
Requires javap on PATH. Records generated bytecode metadata, not SDK source.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import zipfile

CLASSES = [
    'com/intellij/openapi/fileEditor/FileEditorManager',
    'com/intellij/openapi/fileEditor/ex/FileEditorManagerEx',
    'com/intellij/platform/backend/navigation/NavigationRequest',
    'com/intellij/platform/ide/navigation/NavigationService',
    'org/jetbrains/plugins/terminal/LocalTerminalDirectRunner',
]


def inspect(output, sdk):
    info = json.loads((sdk / 'product-info.json').read_text())
    build = f"{info['productCode']}-{info['buildNumber']}"
    target = output / build
    target.mkdir(parents=True, exist_ok=True)
    remaining, records = set(CLASSES), []
    jars = sorted(list((sdk / 'lib').glob('*.jar')) +
                  list((sdk / 'plugins/terminal/lib').glob('*.jar')))
    for jar in jars:
        with zipfile.ZipFile(jar) as archive:
            found = remaining.intersection(n[:-6] for n in archive.namelist() if n.endswith('.class'))
            for name in sorted(found):
                verbose = subprocess.check_output(['javap', '-v', '-p', '-classpath', str(jar), name.replace('/', '.')], text=True)
                body = verbose[verbose.index('\n{') + 2:]
                lines, keep = [], True
                for line in body.splitlines():
                    if line.startswith('  ') and not line.startswith('    '):
                        keep = True
                    if line.strip() in ('Code:', 'kotlin.Metadata('):
                        keep = False
                    if keep:
                        lines.append(line)
                (target / (name.rsplit('/', 1)[-1] + '.txt')).write_text('\n'.join(lines) + '\n')
                records.append({'class': name, 'jar': str(jar.relative_to(sdk)),
                                'class_sha256': hashlib.sha256(archive.read(name + '.class')).hexdigest(),
                                'jar_sha256': hashlib.sha256(jar.read_bytes()).hexdigest()})
                remaining.remove(name)
    (target / 'sdk.json').write_text(json.dumps({'product': info['productCode'], 'build': info['buildNumber'], 'classes': records, 'missing': sorted(remaining)}, indent=2) + '\n')
    if remaining:
        raise SystemExit(f'{build}: missing {remaining}')


if __name__ == '__main__':
    for sdk in sys.argv[2:]:
        inspect(Path(sys.argv[1]), Path(sdk))
